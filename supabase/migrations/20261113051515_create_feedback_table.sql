/*
# Create feedback table

1. New Tables
- `feedback`
  - `id` (bigint, primary key, identity)
  - `name` (text, optional sender name, max 120 chars)
  - `email` (text, optional sender email, max 200 chars)
  - `message` (text, required, 1 to 2000 chars)
  - `created_at` (timestamptz, defaults to now)

2. Security
- Row level security is enabled on `feedback`.
- The public app role can only INSERT new feedback rows; it cannot read, edit or delete existing feedback.
- Only the INSERT verb is granted, and only the columns the form submits.

3. Notes
- The app has no sign-in, so the anon and authenticated roles are the only ones that submit feedback.
- Length checks are enforced in the database as a second line of defence.
*/

CREATE TABLE IF NOT EXISTS feedback (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text CHECK (name IS NULL OR char_length(name) <= 120),
  email text CHECK (email IS NULL OR char_length(email) <= 200),
  message text NOT NULL CHECK (char_length(message) BETWEEN 1 AND 2000),
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE feedback ENABLE ROW LEVEL SECURITY;

GRANT INSERT (name, email, message) ON feedback TO anon, authenticated;

DROP POLICY IF EXISTS "anon_insert_feedback" ON feedback;
CREATE POLICY "anon_insert_feedback" ON feedback FOR INSERT
TO anon, authenticated WITH CHECK (true);
